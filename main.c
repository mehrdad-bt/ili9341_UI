/**
* @brief Function implementing the ButtonTask thread.
* @param argument: Not used
* @retval None
*/
/* USER CODE END Header_StartButtonTask */
void StartButtonTask(void *argument)
{
  /* USER CODE BEGIN StartButtonTask */
	 ButtonEventType event;
  /* Infinite loop */
  for(;;)
  {
		        if (xQueueReceive(buttonQueue, &event, portMAX_DELAY)) {
            switch(current_page) {
                case PAGE_MAIN:
                    MainPage_ButtonHandler(event);
                    break;
                case PAGE_OCS:
                    Osc_ButtonHandler(event);
                    break;								
                case PAGE_FAN:
                    FanPage_ButtonHandler(event);
                    break;								
                case PAGE_SETTING:
                    SettingsPage_ButtonHandler(event);
                    break;
								case PAGE_COLOR_SELECT:
                    ColorsPage_ButtonHandler(event);
                    break;
									case PAGE_TEMP:
                    TempPage_ButtonHandler(event);
                    break;
            }
        }

    osDelay(1);
  }
  /* USER CODE END StartButtonTask */
}

